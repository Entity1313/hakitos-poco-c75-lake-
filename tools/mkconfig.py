#!/usr/bin/env python3
"""
Resolve a HakiOS defconfig into .config, following its #include lines.

  tools/mkconfig.py --defconfig configs/lake_defconfig --out .config \
      --header include/generated/lake_config.h --include-dir ../hakios/configs

A defconfig is a list of CONFIG_* lines with `#include name` in it, exactly as the shared kernel
tree writes them. Includes are looked up next to the including file, then in --include-dir (a
colon-separated list), then in configs/. `common_defconfig` and `mt6768.config` live in the common
repository; when it is not checked out they are reported and skipped, which leaves a device-only
configuration -- enough for mtkloader and for reviewing this phone's fragment, not enough to build
the kernel. Any other missing include is an error.
"""
import argparse
import os
import re
import sys

INCLUDE = re.compile(r'^\s*#\s*include\s+(?:[<"]([^>"]+)[>"]|([^\s]+))\s*$')
CONFIG = re.compile(r'^(CONFIG_[A-Za-z0-9_]+)=(.*?)\s*$')
COMMON_FRAGMENTS = {'common_defconfig', 'mt6768.config'}


def find(name, here, include_dirs):
    candidates = [os.path.join(here, name)] + [os.path.join(d, name) for d in include_dirs]
    for path in candidates:
        if os.path.isfile(path):
            return path
    return None


def resolve(path, include_dirs, seen, out, missing, depth=0):
    if depth > 16:
        raise SystemExit('mkconfig: include nesting is too deep at %s' % path)
    real = os.path.realpath(path)
    if real in seen:
        return
    seen.add(real)
    here = os.path.dirname(os.path.abspath(path))
    out.append('# ---- %s ----' % os.path.relpath(path))
    try:
        lines = open(path, encoding='utf-8').read().splitlines()
    except OSError as e:
        raise SystemExit('mkconfig: cannot read %s: %s' % (path, e))
    for line in lines:
        m = INCLUDE.match(line)
        if not m:
            out.append(line)
            continue
        name = m.group(1) or m.group(2)
        child = find(name, here, include_dirs)
        if child is None:
            base = os.path.basename(name)
            if base in COMMON_FRAGMENTS:
                missing.append(base)
                out.append('# %s: not found in this checkout (common kernel tree); skipped' % base)
                continue
            raise SystemExit('mkconfig: %s includes %s, which is not in %s'
                             % (path, name, os.pathsep.join([here] + include_dirs)))
        resolve(child, include_dirs, seen, out, missing, depth + 1)


def emit_header(lines, path):
    defines = []
    for line in lines:
        m = CONFIG.match(line)
        if not m:
            continue
        name, value = m.group(1), m.group(2).strip()
        if value in ('y', 'n'):
            value = '1' if value == 'y' else '0'
        elif not (re.fullmatch(r'[-+]?(0x[0-9a-fA-F]+|\d+)', value) or
                  (len(value) >= 2 and value[0] == '"' and value[-1] == '"')):
            value = '"%s"' % value.replace('"', '\\"')
        defines.append('#define %-32s %s' % (name, value))
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as f:
        f.write('/* Generated by tools/mkconfig.py. Do not edit. */\n')
        f.write('#ifndef HAKIOS_GENERATED_CONFIG_H\n#define HAKIOS_GENERATED_CONFIG_H\n\n')
        if defines:
            f.write('\n'.join(defines) + '\n')
        else:
            f.write('/* no CONFIG_* lines */\n')
        f.write('\n#endif /* HAKIOS_GENERATED_CONFIG_H */\n')


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    ap.add_argument('--defconfig', required=True)
    ap.add_argument('--out', default='.config')
    ap.add_argument('--header')
    ap.add_argument('--include-dir', default='', help='colon-separated extra directories')
    args = ap.parse_args()

    include_dirs = [d for d in args.include_dir.split(os.pathsep) if d]
    lines, missing = [], []
    resolve(args.defconfig, include_dirs, set(), lines, missing)
    with open(args.out, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines).rstrip() + '\n')
    if args.header:
        emit_header(lines, args.header)
    if missing:
        sys.stderr.write('mkconfig: skipped %s (not in this checkout; set HAKIOS_KERNEL_TREE '
                         'to the shared kernel tree)\n' % ', '.join(sorted(set(missing))))
    print('mkconfig: %s -> %s (%d lines)' % (args.defconfig, args.out, len(lines)))


if __name__ == '__main__':
    main()
